"""Author a static engineering example; read only immutable V6 entity identity."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from aegis_dc.evidence_ledger import validate_ledger


def build():
    # No parameter, runtime, fault, seed, or current-state value is read here.
    identity = json.loads((ROOT / 'configs/full-facility-mainline-reserve-v6.json').read_text(encoding='utf-8'))
    document = dict(schema='aegisdc-evidence-ledger-v1', id='V6-evidence-engineering-example-v1',
                    facility_id=identity['id'], basis='synthetic_assumption', time_unit='s',
                    entity_ids=[entity['id'] for entity in identity['entities']], observables=[], sources=[], records=[])
    for identifier, quantity, value_type, unit in [
        ('nameplate_power', 'power', 'number', 'W'),
        ('maintenance_reported', 'binary', 'boolean', '1'),
        ('temperature', 'temperature', 'number', 'K'),
        ('flow', 'volume_flow', 'number', 'm3/s'),
        ('input_power', 'power', 'number', 'W'),
        ('vibration_reported', 'binary', 'boolean', '1'),
        ('temperature_offset', 'temperature_offset', 'number', 'K'),
        ('supervisory_online_reported', 'binary', 'boolean', '1'),
    ]:
        document['observables'].append(dict(id=identifier, quantity=quantity, value_type=value_type, unit=unit))
    for identifier, kind, target, observables, dependency in [
        ('asset-register', 'asset_record', 'rectifier', ['nameplate_power'], None),
        ('maintenance-log', 'maintenance_history', 'filter', ['maintenance_reported'], None),
        ('point_temperature', 'fixed_sensor', 'immersion', ['temperature'], 'temperature-signal-chain'),
        ('point_flow', 'fixed_sensor', 'intake_pump', ['flow'], None),
        ('point_power', 'fixed_sensor', 'rectifier', ['input_power'], None),
        ('work-order-inbox', 'work_order', 'immersion', ['temperature'], 'temperature-signal-chain'),
        ('operator-report', 'human_report', 'filter', ['vibration_reported'], None),
        ('local-controller-log', 'control_record', 'local_controller', ['supervisory_online_reported'], None),
        ('handheld-thermometer', 'handheld', 'immersion', ['temperature'], None),
        ('handheld-offset-meter', 'handheld', 'plate_hx', ['temperature_offset'], None),
    ]:
        document['sources'].append(dict(id=identifier, kind=kind, basis='synthetic_assumption',
            target_ids=[target], observable_ids=observables, dependency_group=dependency,
            source_note='Static engineering input, not generated by a plant, worker execution, or real site telemetry.'))
    registry = {row['id']: row for row in document['observables']}

    def record(identifier, source, target, observable, value, observed, arrived, until,
               status='bounded', error=0, origin=None, copied_from=None):
        document['records'].append(dict(id=identifier, source_id=source, target_id=target,
            observable_id=observable, unit=registry[observable]['unit'], value=value,
            observed_at_s=observed, arrived_at_s=arrived, valid_until_s=until,
            quality=dict(status=status, error_bound=error,
                         note='Declared fixture quality only; unknown remains unknown; no field calibration.'),
            provenance=dict(origin_id=origin or 'origin-' + identifier, copied_from_record_id=copied_from)))

    record('design-rating', 'asset-register', 'rectifier', 'nameplate_power', 600000, -86400, -3600, None)
    record('maintenance-history', 'maintenance-log', 'filter', 'maintenance_reported', True,
           -600, -300, 600, 'reported', None)
    record('zero-power', 'point_power', 'rectifier', 'input_power', 0, 2, 2, 10, error=5)
    record('flow-zero', 'point_flow', 'intake_pump', 'flow', 0, 1, 3, 10, error=.001)
    record('human-false', 'operator-report', 'filter', 'vibration_reported', False, 7, 8, 15, 'unknown', None)
    record('control-offline', 'local-controller-log', 'local_controller', 'supervisory_online_reported',
           False, 9, 9, 20, 'reported', None)
    record('copy-before-alarm', 'work-order-inbox', 'immersion', 'temperature', 315, 10, 11, 25,
           error=.5, origin='temperature-observation-10', copied_from='alarm-t10')
    record('alarm-t10', 'point_temperature', 'immersion', 'temperature', 315, 10, 12, 25,
           error=.5, origin='temperature-observation-10')
    record('handheld-negative', 'handheld-offset-meter', 'plate_hx', 'temperature_offset', -2, 10, 14, 25, error=.2)
    record('late-history', 'maintenance-log', 'filter', 'maintenance_reported', False,
           -60, 16, -10, 'unknown', None)
    record('handheld-conflict', 'handheld-thermometer', 'immersion', 'temperature', 300, 10, 18, 25, error=.5)
    record('missing-flow', 'point_flow', 'intake_pump', 'flow', None, 20, 20, 30, 'unknown', None)
    return validate_ledger(document)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    with args.output.open('x', encoding='utf-8', newline='\n') as stream:
        stream.write(json.dumps(build(), ensure_ascii=False, indent=2, allow_nan=False) + '\n')
